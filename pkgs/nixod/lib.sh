# shellcheck shell=bash
# Helpers shared by every nixod command.
#
# A command is a list of named steps (`step`). External commands that change
# something go through `run`: with --dry-run they are printed, not run.

DRY_RUN=${DRY_RUN:-0}
YES=${YES:-0}

step() { printf '\n==> %s\n' "$*" >&2; }
info() { printf '    %s\n' "$*" >&2; }
warn() { printf 'nixod: warning: %s\n' "$*" >&2; }
die() {
  printf 'nixod: %s\n' "$*" >&2
  exit 1
}

# run <command...>: runs it, or prints it with --dry-run.
run() {
  if [[ $DRY_RUN == 1 ]]; then
    local -a shown=("$@")
    [[ $1 == nix_ ]] && shown=(nix --extra-experimental-features "nix-command flakes" "${@:2}")
    printf '    $' >&2
    printf ' %q' "${shown[@]}" >&2
    printf '\n' >&2
  else
    "$@"
  fi
}

# confirm <what> <word>: the user types <word> to go on. --yes skips the
# question; it is for an agent that has already asked the user.
confirm() {
  local what=$1 word=$2 answer
  [[ $DRY_RUN == 1 || $YES == 1 ]] && return 0
  [[ -t 0 ]] || die "$what: needs confirmation. Ask the user, then re-run with --yes."
  printf '%s\n' "$what" >&2
  read -r -p "Type '$word' to go on: " answer
  [[ $answer == "$word" ]] || die "not confirmed, nothing done"
}

# new_syncthing_identity <dir>: Syncthing cert.pem + key.pem in <dir>
# (only those two files: the config is generated by NixOS).
new_syncthing_identity() {
  local dir=$1 tmp
  if [[ $DRY_RUN == 1 ]]; then
    run syncthing generate --home "<tmp>"
    run install -m 600 "<tmp>/cert.pem" "<tmp>/key.pem" "$dir/"
    return
  fi
  tmp=$(mktemp -d)
  syncthing generate --home "$tmp" >/dev/null 2>&1 || {
    rm -rf "$tmp"
    die "syncthing generate failed"
  }
  install -d -m 700 "$dir"
  install -m 600 "$tmp/cert.pem" "$tmp/key.pem" "$dir/"
  rm -rf "$tmp"
}

# nix with flakes on, whatever this machine's nix.conf says (the first host
# may not run nixod's config yet).
nix_() { nix --extra-experimental-features "nix-command flakes" "$@"; }

syncthing_id() { syncthing --home "$1" device-id; }

# public_key <file.pub>: "type base64 comment" of an SSH public key.
public_key() { tr -d '\n' <"$1"; }

# ---- Machine config (written by NixOS to /etc/nixod/config) ----
# NIXOD_NAME, NIXOD_ROLE, NIXOD_REPO_URL, NIXOD_BRANCH, NIXOD_REPO_PATH, ...
# Values already in the environment win (tests, manual runs).
load_config() {
  local file=${NIXOD_CONFIG:-/etc/nixod/config} line key
  if [[ -r $file ]]; then
    while IFS= read -r line; do
      [[ $line =~ ^([A-Z_]+)= ]] || continue
      key=${BASH_REMATCH[1]}
      [[ -n ${!key:-} ]] || eval "$line"
    done <"$file"
  fi
  NIXOD_SIGNERS=${NIXOD_SIGNERS:-/etc/nixod/allowed_signers}
  NIXOD_STATE=${NIXOD_STATE:-/var/lib/nixod}
  NIXOD_BRANCH=${NIXOD_BRANCH:-main}
}

# The commit this machine runs: the last update nixod applied, else the
# revision the running system was built from.
running_rev() {
  local rev
  rev=$(cat "$NIXOD_STATE/revision" 2>/dev/null || true)
  # The running system's own nixos-version has its revision built in.
  [[ -n $rev ]] || rev=$(/run/current-system/sw/bin/nixos-version --configuration-revision 2>/dev/null || true)
  printf '%s' "$rev"
}

# verify <repo> <cur> <new> <signers>: may <new> be applied on top of <cur>?
# Prints why not and returns 1. The signers file must come from the running
# system, never from the commit being checked.
verify() {
  local repo=$1 cur=$2 new=$3 signers=$4
  if ! git -C "$repo" merge-base --is-ancestor "$cur" "$new" 2>/dev/null; then
    echo "$new does not build on the running commit $cur (rewritten history or rollback)"
    return 1
  fi
  if ! git -C "$repo" -c gpg.ssh.allowedSignersFile="$signers" verify-commit "$new" >/dev/null 2>&1; then
    echo "$new is not signed by a trusted machine"
    return 1
  fi
}

# expand_home <path>: ~/x → $HOME/x
expand_home() { printf '%s' "${1/#\~/$HOME}"; }

# fetch_request <pr number | branch>: fetches a join request and the branch
# from origin, prints the request's commit. A PR number reads GitHub's
# refs/pull/<n>/head; anything else is a branch name.
fetch_request() {
  local id=$1 src
  if [[ $id =~ ^[0-9]+$ ]]; then src=refs/pull/$id/head; else src=refs/heads/$id; fi
  git fetch --quiet origin \
    "+refs/heads/$NIXOD_BRANCH:refs/remotes/origin/$NIXOD_BRANCH" \
    "+$src:refs/nixod/request/${id//\//-}" >&2 || die "can't fetch $id from origin"
  git rev-parse "refs/nixod/request/${id//\//-}"
}

# review_marker <id>: where `nixod review` records the commit it reviewed.
review_marker() { printf '%s/nixod-reviewed-%s' "$(git rev-parse --absolute-git-dir)" "${1//\//-}"; }
